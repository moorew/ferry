// Generates the phone apps' design files from design/ (SPEC 21.5), the only source:
//   src/theme/tokens.ts                     colours, type, radii, motion
//   src/ui/icon-shapes.ts                   the 24-grid icons for react-native-svg
//   native-assets/ios/Icons.xcassets/       template images for tabs (copied at prebuild)
//   native-assets/android/drawable/         vector drawables for the tile and shortcuts
// `node scripts/design.mjs --check` fails if any output is out of date.

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const design = join(root, '..', 'design');
const check = process.argv.includes('--check');
const outputs = new Map();

function emit(path, text) {
  outputs.set(join(root, path), text);
}

// Tokens.
const tokens = JSON.parse(readFileSync(join(design, 'tokens', 'tokens.json'), 'utf8'));
const values = (group) =>
  Object.fromEntries(Object.entries(group).filter(([k]) => !k.startsWith('$')).map(([k, v]) => [camel(k), v.$value]));
function camel(s) {
  return s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
}
const styles = Object.fromEntries(
  Object.entries(tokens.font.style).map(([name, s]) => [
    camel(name),
    {
      family: s.family,
      size: s.size,
      weight: s.weight,
      lineHeight: s.lineHeight ? Math.round(s.size * s.lineHeight) : undefined,
      tracking: s.tracking ? Math.round(parseFloat(s.tracking) * s.size * 100) / 100 : undefined,
      uppercase: s.transform === 'uppercase' || undefined,
    },
  ]),
);
const motion = Object.fromEntries(
  Object.entries(tokens.motion)
    .filter(([, v]) => typeof v === 'object' && 'ms' in v)
    .map(([k, v]) => [camel(k), v.ms]),
);
const radius = Object.fromEntries(
  Object.entries(tokens.radius).filter(([, v]) => typeof v === 'number').map(([k, v]) => [camel(k), v]),
);
emit(
  'src/theme/tokens.ts',
  `// Generated by scripts/design.mjs from design/tokens/tokens.json. Don't edit.

export const light = ${JSON.stringify(values(tokens.color.light), null, 2)} as const;

export const dark = ${JSON.stringify(values(tokens.color.dark), null, 2)} as const;

/** Assigned in join order; always shown with the device name. */
export const deviceColours = ${JSON.stringify(tokens.color.device.values)} as const;

/** Pairing QR codes: the same in both themes. */
export const qr = ${JSON.stringify({ ink: tokens.color.qr.ink.$value, paper: tokens.color.qr.paper.$value })} as const;

export const radius = ${JSON.stringify({ ...radius, avatar: tokens.radius.avatar }, null, 2)} as const;

export const type = ${JSON.stringify(styles, null, 2)} as const;

/** Durations in ms. Reduced motion: fades only, at most \`reducedMaxMs\`. */
export const motion = ${JSON.stringify({ ...motion, reducedMaxMs: 120 }, null, 2)} as const;

export type Palette = { [K in keyof typeof light]: string };
`,
);

// Icons.
const iconDir = join(design, 'assets', 'icons');
const icons = readdirSync(iconDir)
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((f) => {
    const svg = readFileSync(join(iconDir, f), 'utf8');
    const body = svg.slice(svg.indexOf('>') + 1, svg.lastIndexOf('</svg>'));
    const shapes = [...body.matchAll(/<(\w+)([^>]*?)\/?>/g)].map(([, tag, rest]) => ({
      tag,
      attrs: Object.fromEntries([...rest.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v])),
    }));
    return { name: f.slice(0, -4), shapes };
  });
for (const { name, shapes } of icons) {
  for (const s of shapes) {
    if (!['path', 'rect', 'circle'].includes(s.tag)) throw new Error(`${name}: unsupported <${s.tag}>`);
  }
}
emit(
  'src/ui/icon-shapes.ts',
  `// Generated by scripts/design.mjs from design/assets/icons. Don't edit.

export type Shape = { tag: 'path' | 'rect' | 'circle'; attrs: Record<string, string> };

export const iconShapes = ${JSON.stringify(Object.fromEntries(icons.map((i) => [i.name, i.shapes])), null, 2)} as const satisfies Record<string, readonly Shape[]>;

export type IconName = keyof typeof iconShapes;
`,
);

const n = (v) => Number(v);
function pathData({ tag, attrs: a }) {
  if (tag === 'path') return a.d;
  if (tag === 'circle') {
    const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)];
    return `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0z`;
  }
  const [x, y, w, h] = [n(a.x), n(a.y), n(a.width), n(a.height)];
  const r = Math.min(n(a.rx ?? 0), w / 2, h / 2);
  if (!r) return `M${x},${y}h${w}v${h}h${-w}z`;
  return (
    `M${x + r},${y}h${w - 2 * r}a${r},${r} 0 0 1 ${r},${r}v${h - 2 * r}a${r},${r} 0 0 1 ${-r},${r}` +
    `h${-(w - 2 * r)}a${r},${r} 0 0 1 ${-r},${-r}v${-(h - 2 * r)}a${r},${r} 0 0 1 ${r},${-r}z`
  );
}
const filled = (s) => s.attrs.fill === 'currentColor';
// Tiles and notifications want white glyphs; launcher shortcuts sit on a light
// circle, so those few also come in the ink colour.
const shortcutIcons = new Set(['paste', 'search', 'pin']);
const vector = (name, shapes, colour) => {
  const c = '#FF' + colour.replace('#', '');
  return shapes
    .map((s) =>
      filled(s)
        ? `  <path android:fillColor="${c}" android:pathData="${pathData(s)}"/>`
        : `  <path android:strokeColor="${c}" android:strokeWidth="1.75" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="${pathData(s)}"/>`,
    )
    .join('\n');
};
for (const { name, shapes } of icons) {
  const id = `tc_${name.replace(/-/g, '_')}`;
  const variants = [[id, '#FFFFFF']];
  if (shortcutIcons.has(name)) variants.push([`${id}_ink`, tokens.color.light.ink.$value]);
  for (const [file, colour] of variants) {
    emit(
      `native-assets/android/drawable/${file}.xml`,
      `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/design.mjs from design/assets/icons/${name}.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
  android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
${vector(name, shapes, colour)}
</vector>
`,
    );
  }
}
for (const { name } of icons) {
  const id = `tc_${name.replace(/-/g, '_')}`;
  const set = `native-assets/ios/Icons.xcassets/${id}.imageset`;
  const svg = readFileSync(join(iconDir, `${name}.svg`), 'utf8').replaceAll('currentColor', '#000000');
  emit(`${set}/${id}.svg`, svg);
  emit(
    `${set}/Contents.json`,
    JSON.stringify(
      {
        images: [{ filename: `${id}.svg`, idiom: 'universal' }],
        info: { author: 'xcode', version: 1 },
        properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
      },
      null,
      2,
    ) + '\n',
  );
}
emit('native-assets/ios/Icons.xcassets/Contents.json', JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2) + '\n');

// Write or compare.
let stale = 0;
for (const [path, text] of outputs) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === text) continue;
  if (check) {
    console.error(`out of date: ${path.slice(root.length + 1)}`);
    stale++;
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
}
if (!check) {
  // Drop outputs for icons that were removed from design/.
  for (const dir of ['native-assets/android/drawable', 'native-assets/ios/Icons.xcassets']) {
    const full = join(root, dir);
    for (const f of readdirSync(full)) {
      const p = join(full, f);
      const keep = [...outputs.keys()].some((o) => o === p || o.startsWith(p + '/'));
      if (!keep) rmSync(p, { recursive: true });
    }
  }
}
if (stale) {
  console.error(`\nRun \`npm run design\` in mobile/ and commit the result.`);
  process.exit(1);
}
